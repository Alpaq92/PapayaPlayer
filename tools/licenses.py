#!/usr/bin/env python3
"""Checks every third-party submodule's license and writes THIRD-PARTY-NOTICES.

Each directory in third_party/ must carry a license file whose text matches an
allowed (permissive) license; copyleft text fails the check (TECH-STACK.md
step 2). Reaktor is checked as one unit: its own NOTICE covers its submodules.

    python tools/licenses.py            check, write THIRD-PARTY-NOTICES.generated.md
    python tools/licenses.py --check    check only
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
THIRD_PARTY = ROOT / "third_party"
OUT = ROOT / "THIRD-PARTY-NOTICES.generated.md"

# Where the license we use is not the first license file in the directory.
# FLAC: libFLAC is BSD (COPYING.Xiph); its tools are GPL and are never built.
LICENSE_FILE = {"flac": "COPYING.Xiph"}

LICENSE_NAMES = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE)(\..*)?$", re.I)

# First match wins, so copyleft is tested before the permissive texts it may quote.
DENIED = [
    ("AGPL", re.compile(r"GNU AFFERO GENERAL PUBLIC LICENSE", re.I)),
    ("LGPL", re.compile(r"GNU LESSER GENERAL PUBLIC LICENSE|GNU LIBRARY GENERAL PUBLIC", re.I)),
    ("GPL", re.compile(r"GNU GENERAL PUBLIC LICENSE", re.I)),
    ("MPL", re.compile(r"Mozilla Public License", re.I)),
]
ALLOWED = [
    ("Apache-2.0", re.compile(r"Apache License,?\s+Version 2\.0", re.I)),
    ("MIT", re.compile(r"Permission is hereby granted, free of charge", re.I)),
    ("BSD", re.compile(r"Redistribution and use in source and binary forms", re.I)),
    ("ISC", re.compile(r"Permission to use, copy, modify, and/or distribute this software", re.I)),
    ("zlib", re.compile(r"This software is provided 'as-is'", re.I)),
    ("BSL-1.0", re.compile(r"Boost Software License", re.I)),
    ("CC0-1.0", re.compile(r"CC0 1\.0|Creative Commons Zero", re.I)),
    ("Unlicense", re.compile(r"This is free and unencumbered software", re.I)),
]


def classify(text):
    for name, pattern in DENIED:
        if pattern.search(text):
            return name, False
    for name, pattern in ALLOWED:
        if pattern.search(text):
            return name, True
    return "unknown", False


def license_files(directory):
    return sorted(p for p in directory.iterdir() if p.is_file() and LICENSE_NAMES.match(p.name))


def main():
    check_only = "--check" in sys.argv[1:]
    problems = []
    sections = []
    for lib in sorted(p for p in THIRD_PARTY.iterdir() if p.is_dir()):
        files = license_files(lib)
        if lib.name in LICENSE_FILE:
            files = [lib / LICENSE_FILE[lib.name]]
        if not files:
            problems.append(f"{lib.name}: no license file")
            continue
        main_file = files[0]
        text = main_file.read_text(encoding="utf-8", errors="replace")
        name, ok = classify(text)
        if not ok:
            problems.append(f"{lib.name}: {main_file.name} reads as {name}")
        sections.append(f"## {lib.name} ({name})\n\n```\n{text.strip()}\n```\n")
    for p in problems:
        print(f"license check: {p}", file=sys.stderr)
    if problems:
        return 1
    if not check_only:
        OUT.write_text("# Third-party notices\n\nGenerated by tools/licenses.py.\n\n"
                       + "\n".join(sections), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} ({len(sections)} libraries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
